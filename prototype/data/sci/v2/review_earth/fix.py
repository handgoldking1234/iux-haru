import json
def load(n): return json.load(open(f'earth_{n}.json'))
def save(n,d): json.dump(d,open(f'earth_{n}.json','w'),ensure_ascii=False,indent=1)
def item(u,t): 
    for it in u['items']:
        if it['t']==t: return it
    raise KeyError(t)
def setd(u,t,d=None,ex=None,newt=None):
    it=item(u,t)
    if d: it['d']=d
    if ex: it['ex']=ex
    if newt: it['t']=newt

